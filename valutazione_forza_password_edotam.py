SPECIAL_CHARS = set(string.punctuation) #i caratteri speciali: !"#$%&\'()*+,-./:;<=>?@[\\]^_`{|}~
COMMON_PATTERNS = [
    r'(.)\1{2,}',  # caratteri ripetuti
    r'(012|123|234|345|456|567|678|789|890|098|987|876|765|654|543|432|321|210)', # sequenze numeriche
    r'(abc|bcd|cde|def|efg|fgh|ghi|hij|ijk|jkl|klm|lmn|mno|nop|opq|pqr|qrs|rst|stu|tuv|uvw|vwx|wxy|xyz)', # sequenze alfabetiche
    r'(qwerty|asdf|zxcv|123456|admin|1234567|12345678|12345|password|Aa123456|Pass@123|admin123|1234567|123123)', # pattern comuni da dizionario
]

def calcola_entropia(password):
    if not password:
        return 0.0
    freq  = Counter(password)
    probs = [f / len(password) for f in freq.values()]
    return -sum(p * math.log2(p) for p in probs)

def conta_pattern_comuni(password):
    pwd_lower = password.lower()
    return sum(1 for p in COMMON_PATTERNS if re.search(p, pwd_lower))

def extract_features(password):
    pwd = str(password)
    n   = len(pwd)
    if n == 0:
        return [0] * 13

    num_upper  = sum(c.isupper()        for c in pwd)
    num_lower  = sum(c.islower()        for c in pwd)
    num_digits = sum(c.isdigit()        for c in pwd)
    num_spec   = sum(c in SPECIAL_CHARS for c in pwd)
    num_unique = len(set(pwd))

    charset_size = (26 if num_lower  > 0 else 0) + \
                   (26 if num_upper  > 0 else 0) + \
                   (10 if num_digits > 0 else 0) + \
                   (32 if num_spec   > 0 else 0)

    return [
        n,  # Lunghezza
        num_upper, # maiuscole
        num_lower, # minuscole
        num_digits, # cifre
        num_spec, # caratteri speciali
        round(num_upper  / n, 4), # Ratio maiuscole
        round(num_digits / n, 4), # Ratio cifre
        round(num_spec   / n, 4), # Ratio speciali
        num_unique,# caratteri unici
        round(num_unique / n, 4), # Ratio unicità
        round(calcola_entropia(pwd), 4), # Entropia di Shannon
        charset_size, # Charset size
        conta_pattern_comuni(pwd), # pattern deboli rilevati
    ]

FEATURE_NAMES = ['length', 'n_upper', 'n_lower', 'n_digits', 'n_special', 'ratio_upper', 'ratio_digits', 'ratio_special','n_unique', 'ratio_unique', 'entropy', 'charset_size', 'n_common_patterns']

